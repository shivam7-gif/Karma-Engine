import chalk from "chalk";
import { StackPilotState } from "../../stackpilot.state.js";
import { KarmaH1Agent } from "./h1.agent.js";

const h1 = new KarmaH1Agent();

export async function h1CoderNode(state: typeof StackPilotState.State) {
  console.log(chalk.magenta.bold("[KARMA H1] Node running..."));

  try {
    const output = await h1.execute(state.plannerOutput, state.architectOutput);
    console.log(chalk.green.bold("[KARMA H1] Node completed"));

    return {
      generatedFiles: output.files,
      generatedProjectName: output.projectName,
    };
  } catch (error: any) {
    const msg = error instanceof Error ? error.message : String(error);
    console.warn(
      chalk.yellow(
        `[KARMA H1] Code generation failed or rate limited (${msg}). Generating starter files from architecture plan...`
      )
    );

    const architect = state.architectOutput as any;
    const projName =
      architect?.projectType?.toLowerCase().replace(/[^a-z0-9-]/gi, "-") ||
      "stackpilot-project";

    const starterFiles = [
      {
        path: "README.md",
        code: `# ${projName}\n\nGenerated by StackPilot AI Engine.\n\n### Tech Stack\n- Frontend: ${architect?.frontend?.framework || "React"} (${architect?.frontend?.language || "TypeScript"})\n- Backend: ${architect?.backend?.framework || "Express"} (${architect?.backend?.language || "TypeScript"})\n- Database: ${architect?.backend?.database || "PostgreSQL"}\n- Caching: ${architect?.infrastructure?.caching || "Redis"}\n\n### Run Instructions\nCheck frontend and backend subdirectories for setup and start scripts.\n`,
        action: "create",
      },
      {
        path: "stackpilot.architecture.json",
        code: JSON.stringify(
          {
            project: projName,
            architecture: state.architectOutput,
            plan: state.plannerOutput,
          },
          null,
          2
        ),
        action: "create",
      },
    ];

    return {
      generatedFiles: starterFiles,
      generatedProjectName: projName,
    };
  }
}

